#!/usr/bin/env node
/**
 * ParkFlows token pipeline (002 tech design T1). Node built-ins only.
 *
 * Reads src/design-system/tokens.json (the single source of design values)
 * and writes two generated, committed files next to it:
 *   tokens.css  CSS custom properties (:root) for the console, the marketing
 *               site and the R2 apps, plus the reduce-motion block.
 *   theme.css   a Tailwind 4 @theme block with the same values, so
 *               utilities like bg-navy-600, p-4 (16px), text-title-1 compile.
 *               R1: no reset of Tailwind's default palette/sizes yet (K3);
 *               lint:styles forbids the defaults in R1 files instead.
 *
 *   npm run tokens            regenerate both files
 *   npm run tokens -- --check fail (exit 1) if either file is stale
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'src', 'design-system');
const SRC = join(DIR, 'tokens.json');
const check = process.argv.includes('--check');

const t = JSON.parse(readFileSync(SRC, 'utf8'));
const HEADER = '/* GENERATED by scripts/build-tokens.mjs from src/design-system/tokens.json.\n   Do not edit by hand: change tokens.json and run `npm run tokens`. */\n';

// ---- helpers ----
const colors = t.color.tokens;
const colorNames = new Set(colors.map((c) => c.name));
/** Resolve "{name}" references to another colour token. */
function refTo(value, prefix) {
  const m = /^\{([a-z0-9-]+)\}$/.exec(value);
  if (!m) return value;
  if (!colorNames.has(m[1])) throw new Error(`Unknown colour reference ${value}`);
  return `var(${prefix}${m[1]})`;
}
const families = t.type.families; // display/text/mono
const typeStyles = t.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
const px = (v) => {
  if (!/^\d+(\.\d+)?px$/.test(v)) throw new Error(`Expected a px value, got ${v}`);
  return v;
};
const list = (name) => (t[name] && t[name].tokens) || [];

// ---- tokens.css ----
function tokensCss() {
  const out = [HEADER, ':root {'];
  out.push('  /* Colour */');
  for (const c of colors) out.push(`  --${c.name}: ${refTo(c.value, '--')};`);
  out.push('', '  /* Type families */');
  for (const [k, v] of Object.entries(families)) out.push(`  --font-${k}: ${v};`);
  out.push('', '  /* Type styles: --type-<name> is a `font` shorthand; size/line-height/tracking also exposed */');
  for (const s of typeStyles) {
    out.push(`  --type-${s.name}: ${s.fontWeight} ${px(s.fontSize)}/${px(s.lineHeight)} var(--font-${s.family});`);
    out.push(`  --text-${s.name}-size: ${s.fontSize};`);
    out.push(`  --text-${s.name}-line: ${s.lineHeight};`);
    out.push(`  --text-${s.name}-tracking: ${s.letterSpacing || 'normal'};`);
  }
  for (const [label, key] of [['Spacing', 'spacing'], ['Radius', 'radius'], ['Elevation', 'shadow'], ['Duration', 'duration'], ['Easing', 'easing'], ['Sizes', 'size'], ['Breakpoints (reference only; media queries use the px values)', 'breakpoint'], ['Layers', 'zIndex']]) {
    out.push('', `  /* ${label} */`);
    for (const tok of list(key)) out.push(`  --${tok.name}: ${tok.value};`);
  }
  out.push('}', '');
  out.push('/* Motion off for people who ask for it (AC-20): every duration becomes 0ms. */');
  out.push('@media (prefers-reduced-motion: reduce) {', '  :root {');
  for (const tok of list('duration')) out.push(`    --${tok.name}: 0ms;`);
  out.push('  }', '}', '');
  return out.join('\n');
}

// ---- theme.css (Tailwind 4) ----
function themeCss() {
  const out = [HEADER, '/* Tailwind 4 theme from the same tokens. R1: Tailwind\'s default palette and sizes are NOT reset yet (K3). */', '@theme {'];
  for (const c of colors) out.push(`  --color-${c.name}: ${refTo(c.value, '--color-')};`);
  out.push('');
  for (const [k, v] of Object.entries(families)) out.push(`  --font-${k}: ${v};`);
  out.push('');
  for (const s of typeStyles) {
    out.push(`  --text-${s.name}: ${s.fontSize};`);
    out.push(`  --text-${s.name}--line-height: ${s.lineHeight};`);
    out.push(`  --text-${s.name}--font-weight: ${s.fontWeight};`);
    if (s.letterSpacing) out.push(`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`);
  }
  out.push('', '  /* 4px grid: p-4 = 16px = space-4 */', '  --spacing: 4px;');
  for (const tok of list('size')) out.push(`  --spacing-${tok.name}: ${tok.value};`);
  out.push('');
  for (const tok of list('radius')) out.push(`  --radius-${tok.name.replace(/^radius-/, '')}: ${tok.value};`);
  out.push('');
  for (const tok of list('shadow')) out.push(`  --shadow-${tok.name.replace(/^shadow-/, '')}: ${tok.value};`);
  out.push('');
  for (const tok of list('breakpoint')) out.push(`  --breakpoint-${tok.name.replace(/^bp-/, '')}: ${tok.value};`);
  out.push('');
  const fast = list('duration').find((d) => d.name === 'duration-fast');
  const ease = list('easing').find((e) => e.name === 'ease-standard');
  for (const e of list('easing')) out.push(`  --ease-${e.name.replace(/^ease-/, '')}: ${e.value};`);
  if (fast) out.push(`  --default-transition-duration: var(--${fast.name});`);
  if (ease) out.push(`  --default-transition-timing-function: ${ease.value};`);
  out.push('}', '');
  return out.join('\n');
}

const files = [
  [join(DIR, 'tokens.css'), tokensCss()],
  [join(DIR, 'theme.css'), themeCss()],
];
let stale = 0;
for (const [file, content] of files) {
  const rel = relative(ROOT, file);
  if (check) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current !== content) {
      stale++;
      console.error(`stale: ${rel} (run \`npm run tokens\`)`);
    } else console.log(`ok: ${rel}`);
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${rel}`);
  }
}
if (stale) process.exit(1);
