await page.getByRole('button', { name: /Role View Simulator/i }).first().click(); await page.waitForTimeout(800);
const row = page.locator('div').filter({ has: page.getByText('QA tmpva', { exact: true }) }).filter({ has: page.getByRole('button', { name: /View as/i }) }).last();
