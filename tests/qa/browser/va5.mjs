import { browser, openPage, login, nav, shot, MASTER, URL } from './lib.mjs';
import fs from 'node:fs';
const fx = JSON.parse(fs.readFileSync(`${process.env.QA_OUT || './qa-out'}/fixtures.json`));
const b = await browser(); const { page, reqs } = await openPage(b, { height: 1000 });
const api = await (await b.newContext()).newPage();
const mt = (await (await api.request.post(URL + '/api/v1/auth/login', { data: { identifier: MASTER, password: 'QaTestPassword#2026' } })).json()).token;
const H = { 'x-session-token': mt };
const cu = await (await api.request.post(URL + '/api/v1/rbac/users', { headers: H, data: { username: 'qa.tmpva', fullName: 'QA tmpva', email: 'qa.tmpva@qa-parkflows.test', roleId: 'role-site-manager', siteScopeType: 'SPECIFIC_SITES', assignedSiteIds: [fx.sites.A.id], status: 'ACTIVE', plainPassword: 'QaTestPassword#2026' } })).json();
